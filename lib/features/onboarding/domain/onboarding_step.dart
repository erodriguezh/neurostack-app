/// The steps in the onboarding flow.
///
/// Each step corresponds to a screen in the onboarding experience.
enum OnboardingStep {
  /// Screen 1: Hook - "You've read the studies"
  hook,

  /// Screen 2: Agitate - "The gap between knowing and doing"
  agitate,

  /// Screen 3: Offer - "What if you just... did the thing?"
  offer,

  /// Screen 4: Disclaimer - "One more thing"
  disclaimer,
}
